import assert from "node:assert/strict";
import test from "node:test";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import { gunzipSync } from "node:zlib";

import { buildAll, buildPremiumNodePackage, canonicalJson, parseArgs, sha256 } from "../scripts/build.mjs";
import { computeCurrentSourceFingerprint } from "../scripts/content/current-source-identity.mjs";

const root = path.resolve(import.meta.dirname, "..");
const trackId = "aws-certified-solutions-architect-associate", nodeId = "identity_federation_and_root_access";
async function workspace(t) {
  const base = await mkdtemp(path.join(tmpdir(), "patternly-premium-current-"));
  t.after(() => rm(base, { recursive: true, force: true }));
  const app = path.join(base, "app"), outputRoot = path.join(base, "output");
  return { rootDirectory: root, appRoot: app, trackId, nodeId, outputRoot };
}

test("Premium payload derives from today's canonical bank and binds its source fingerprint", async (t) => {
  const options = await workspace(t), result = await buildPremiumNodePackage(options);
  const bytes = await readFile(result.packageFile), payloadBytes = gunzipSync(bytes), payload = JSON.parse(payloadBytes);
  const sourceRoot = path.join(options.outputRoot, "source-check");
  const source = await buildAll({ rootDirectory: root, outputRoot: sourceRoot });
  const track = source.artifacts.find((entry) => entry.trackId === trackId);
  assert.deepEqual(payload.items, track.artifact.questions.filter((item) => item.nodeId === nodeId));
  assert.equal(payload.items.length, 123); assert.equal(result.derivation.mentalUnitIds.length, 6);
  assert.equal(sha256(payloadBytes), result.offer.artifactSha256); assert.equal(sha256(bytes), result.manifest.packageSha256);
  assert.equal(result.derivation.sourceArtifactSha256, sha256(track.artifactBytes));
  assert.equal(result.derivation.currentSourceFingerprint, computeCurrentSourceFingerprint({ built: source }));
  const appRoot = path.resolve(process.env.PATTERNLY_FRONTEND_ROOT ?? path.join(root, "../patternly"));
  const { verifyNodePackage } = await import(pathToFileURL(path.join(appRoot, "src/content/runtime/nodeContentPackage.ts")).href);
  const headers = new Headers({
    "content-type": "application/gzip",
    "content-length": String(bytes.length),
    "x-content-artifact-size-bytes": String(result.manifest.artifactSizeBytes),
    "x-content-package-sha256": result.manifest.packageSha256,
    "x-content-artifact-sha256": result.manifest.artifactSha256,
    "x-content-version": result.manifest.contentVersion,
    "x-content-release-id": result.manifest.contentReleaseId,
    "x-content-minimum-app-version": result.manifest.minimumAppVersion,
  });
  const verified = await verifyNodePackage({
    trackId,
    nodeId,
    packageBytes: new Uint8Array(bytes),
    headers,
    appVersion: "0.1.0",
    hash: { async sha256Bytes(value) { return createHash("sha256").update(value).digest("hex"); } },
  });
  assert.deepEqual(verified.payload.items, payload.items);
  assert.equal(verified.identity.artifactSha256, result.manifest.artifactSha256);
  assert.equal(verified.identity.contentVersion, result.manifest.contentVersion);
  assert.equal(verified.identity.trackId, trackId);
  assert.equal(verified.identity.nodeId, nodeId);
  assert.equal(result.offerPath, undefined);
  await assert.rejects(readFile(path.join(options.appRoot, "src/content/generated/premium-node-offer.json")), { code: "ENOENT" });
  const repeated = await buildPremiumNodePackage(options);
  assert.deepEqual(repeated.manifest, result.manifest);
  assert.deepEqual(await readFile(repeated.packageFile), bytes);
});

test("Premium source derivation does not depend on stale APP bundles", async (t) => {
  const options = await workspace(t);
  const appPackage = path.join(options.appRoot, "src/content/generated/canonical-content", `${trackId}.json`);
  const appLock = path.join(options.appRoot, "src/content/generated/canonical-content/content-lock.json");
  await mkdir(path.dirname(appPackage), { recursive: true });
  await writeFile(appPackage, "stale bytes");
  await writeFile(appLock, "stale lock");
  const result = await buildPremiumNodePackage(options);
  assert.equal(result.derivation.sourceArtifactSha256, result.derivation.selectedApplicationArtifactSha256);
});

test("only explicit apply-offer writes APP metadata", async (t) => {
  const options = await workspace(t), result = await buildPremiumNodePackage({ ...options, applyOffer: true });
  const offer = JSON.parse(await readFile(result.offerPath, "utf8"));
  assert.equal(offer.offer.artifactSha256, result.offer.artifactSha256);
  assert.equal(offer.offer.trackId, trackId);
});

test("Free or unknown node is rejected; current output replaces stale generated bytes", async (t) => {
  for (const rejected of ["aws_secure_architecture_foundations", "missing-node"]) {
    await assert.rejects(buildPremiumNodePackage({ ...await workspace(t), nodeId: rejected }), /non-Free|capacity/u);
  }
  const options = await workspace(t), result = await buildPremiumNodePackage(options);
  await writeFile(result.packageFile, Buffer.from("stale generated package"));
  const refreshed = await buildPremiumNodePackage(options);
  assert.notDeepEqual(await readFile(refreshed.packageFile), Buffer.from("stale generated package"));
  assert.equal(parseArgs(["build-premium-node", "--track", trackId, "--node", nodeId, "--apply-offer"]).applyOffer, true);
  assert.throws(() => parseArgs(["build-premium-node", "--track", trackId]), /required/u);
  assert.throws(() => parseArgs(["build", "--track", trackId, "--apply-offer"]), /require build-premium/u);
});
